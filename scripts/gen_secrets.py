"""PlatformIO pre-build hook: generate inkdeck_secrets.h from the gitignored .env.

Settings: WIFI_SSID and WIFI_PASSWORD (the network that SYNC TIME, and later the network
screens, join), TIMEZONE (a POSIX TZ string, so local time follows daylight saving; empty
means UTC), and LATITUDE/LONGITUDE in decimal degrees (sunrise and sunset on the Clock, the
Weather forecast; optional, but both or neither).

The secrets go into a header in the build directory rather than -D flags, so they never appear
on compiler command lines or in verbose build logs, and any character in a Wi-Fi password
survives intact: every byte that isn't an ASCII letter or digit is written as a 3-digit octal
escape. The header is rewritten only when its content changes, so an unchanged .env doesn't
trigger a rebuild.

Wi-Fi is optional: with no .env, or an empty WIFI_SSID, the header says WIFI_CONFIGURED 0 and
the firmware builds without a network. A value that is set but invalid produces a header that
#errors, so the build stops with the reason instead of flashing credentials that can't work.

Environment variables of the same name override .env, e.g. for a one-off build on another
network.

Adapted from https://github.com/onionhammer/lollipop-smell (scripts/gen_secrets.py).
"""
import os
import re

Import("env")  # noqa: F821 - SCons injects Import into extra scripts

HEADER = "inkdeck_secrets.h"
KEYS = ("WIFI_SSID", "WIFI_PASSWORD", "TIMEZONE", "LATITUDE", "LONGITUDE")
DEFAULT_TIMEZONE = "UTC0"

# POSIX TZ, the only form newlib's tzset() understands: std offset [dst [offset] [,start,end]],
# e.g. CST6CDT,M3.2.0,M11.1.0. Names are 3+ letters or <quoted>; offsets are hours west of UTC.
_TZ_NAME = r"(?:[A-Za-z]{3,}|<[A-Za-z0-9+-]{3,}>)"
_TZ_OFFSET = r"[+-]?\d{1,2}(?::\d{2}){0,2}"
_TZ_RULE = r"(?:M\d{1,2}\.[1-5]\.[0-6]|J?\d{1,3})(?:/[+-]?\d{1,3}(?::\d{2}){0,2})?"
TZ_RE = re.compile(
    r"^%s%s(?:%s(?:%s)?(?:,%s,%s)?)?$"
    % (_TZ_NAME, _TZ_OFFSET, _TZ_NAME, _TZ_OFFSET, _TZ_RULE, _TZ_RULE)
)
DEGREES_RE = re.compile(r"^[+-]?\d{1,3}(?:\.\d+)?$")


def degrees(text, limit):
    """The value as a float within +-limit, or None."""
    if not DEGREES_RE.match(text):
        return None
    value = float(text)
    return value if -limit <= value <= limit else None


def parse_env_file(path):
    values = {}
    if not os.path.isfile(path):
        return values
    # utf-8-sig and the \r strip cope with files saved by Notepad (BOM + CRLF).
    with open(path, encoding="utf-8-sig") as f:
        for raw in f:
            line = raw.rstrip("\r\n").strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("export "):
                line = line[len("export "):].lstrip()
            key, sep, value = line.partition("=")
            if not sep:
                continue
            value = value.strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            values[key.strip()] = value
    return values


def c_string(value):
    out = []
    for b in value.encode("utf-8"):
        ch = chr(b)
        out.append(ch if b < 128 and ch.isalnum() else "\\%03o" % b)
    return '"' + "".join(out) + '"'


def build_header(values):
    errors = []
    lines = ["// Generated by scripts/gen_secrets.py from .env - do not edit or commit.", "#pragma once"]

    timezone = values.get("TIMEZONE") or DEFAULT_TIMEZONE
    if not TZ_RE.match(timezone):
        errors.append(
            "TIMEZONE must be a POSIX TZ string such as CST6CDT,M3.2.0,M11.1.0"
            " (not an IANA name like America/Chicago)"
        )

    ssid = values.get("WIFI_SSID", "")
    password = values.get("WIFI_PASSWORD")
    if ssid:
        if len(ssid.encode("utf-8")) > 32:
            errors.append("WIFI_SSID must be at most 32 bytes")
        if password is None:
            errors.append("WIFI_PASSWORD is missing (set it empty for an open network)")
        elif password and not (
            8 <= len(password.encode("utf-8")) <= 63 or re.fullmatch(r"[0-9A-Fa-f]{64}", password)
        ):
            errors.append("WIFI_PASSWORD must be empty, 8-63 bytes, or a 64-hex-digit PSK")

    lat_text = values.get("LATITUDE", "")
    lon_text = values.get("LONGITUDE", "")
    location = None
    if lat_text or lon_text:
        lat, lon = degrees(lat_text, 90), degrees(lon_text, 180)
        if lat is None or lon is None:
            errors.append(
                "LATITUDE and LONGITUDE must both be set, in decimal degrees"
                " (north and east positive, e.g. 41.88 and -87.63)"
            )
        else:
            location = (lat, lon)

    if errors:
        lines += ['#error "%s: see .env.example"' % e for e in errors]
        return "\n".join(lines) + "\n", errors, False

    lines.append("#define TIMEZONE %s" % c_string(timezone))
    if location:
        lines += [
            "#define LOCATION_CONFIGURED 1",
            "#define LATITUDE (%.5ff)" % location[0],
            "#define LONGITUDE (%.5ff)" % location[1],
        ]
    else:
        lines += ["#define LOCATION_CONFIGURED 0", "#define LATITUDE 0.0f", "#define LONGITUDE 0.0f"]
    if ssid:
        lines += [
            "#define WIFI_CONFIGURED 1",
            "#define WIFI_SSID %s" % c_string(ssid),
            "#define WIFI_PASSWORD %s" % c_string(password),
        ]
    else:
        lines += ["#define WIFI_CONFIGURED 0", '#define WIFI_SSID ""', '#define WIFI_PASSWORD ""']
    return "\n".join(lines) + "\n", errors, bool(ssid)


def main():
    project_dir = env.subst("$PROJECT_DIR")  # noqa: F821 - __file__ is undefined under SCons
    values = parse_env_file(os.path.join(project_dir, ".env"))
    values.update({k: os.environ[k] for k in KEYS if k in os.environ})

    content, errors, configured = build_header(values)

    out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, HEADER)
    try:
        with open(out_path, encoding="utf-8") as f:
            unchanged = f.read() == content
    except OSError:
        unchanged = False
    if not unchanged:
        with open(out_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)

    env.Append(CPPPATH=[out_dir])  # noqa: F821
    for e in errors:
        print("gen_secrets: %s (the firmware build will fail)" % e)
    if not errors and not configured:
        print("gen_secrets: no WIFI_SSID in .env; building without Wi-Fi")


main()
