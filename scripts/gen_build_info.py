"""PlatformIO pre-build hook: generate inkdeck_build.h with the build's version and git commit.

INKDECK_VERSION is the firmware's version, which the updater (src/ota.h) compares with the latest
GitHub release's:
  - the INKDECK_VERSION environment variable, a leading "v" dropped (the release workflow,
    .github/workflows/release.yml, sets it from the tag);
  - else from the nearest v<major>.<minor>.<patch> tag: "0.2.0" on the tagged commit itself,
    "0.2.0+5" five commits after it;
  - else "0.0.0+<commits>" (no tag yet), or "0.0.0" outside a git checkout.

INKDECK_BUILD_ID is the short commit hash, with a "+" when the working tree has uncommitted
changes ("425d25c", "425d25c+"), or "dev" outside a git checkout. The System screen shows both,
so after an update you can see which build the board is running.

The header goes into the build directory and is rewritten only when its content changes, so only
the file that includes it (src/sysinfo.cpp) recompiles after a commit.
"""
import os
import re
import subprocess

Import("env")  # noqa: F821 - SCons injects Import into extra scripts

HEADER = "inkdeck_build.h"
# A release tag without its "v": 0.2.0, or a pre-release such as 0.3.0-rc1.
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$")
# git describe --long: v0.2.0-5-g1a2b3c4 (the tag, commits since, the commit).
DESCRIBE_RE = re.compile(r"^v(.+)-(\d+)-g[0-9a-f]+$")


def git(project_dir, *args):
    try:
        return subprocess.run(
            ["git", *args], cwd=project_dir, capture_output=True, text=True, check=True, timeout=10
        ).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None


def build_id(project_dir):
    commit = git(project_dir, "rev-parse", "--short", "HEAD")
    if not commit:
        return "dev"
    dirty = git(project_dir, "status", "--porcelain", "--untracked-files=no")
    return commit + ("+" if dirty else "")


def version(project_dir):
    given = os.environ.get("INKDECK_VERSION", "").strip()
    if given:
        given = given[1:] if given.startswith("v") else given
        if not VERSION_RE.match(given):
            print("gen_build_info: INKDECK_VERSION=%s isn't <major>.<minor>.<patch>" % given)
            env.Exit(1)  # noqa: F821
        return given
    described = git(project_dir, "describe", "--tags", "--long", "--match", "v[0-9]*")
    m = DESCRIBE_RE.match(described or "")
    if m and VERSION_RE.match(m.group(1)):
        return m.group(1) if m.group(2) == "0" else "%s+%s" % (m.group(1), m.group(2))
    commits = git(project_dir, "rev-list", "--count", "HEAD")
    return "0.0.0+" + commits if commits else "0.0.0"


def main():
    project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
    content = (
        "// Generated by scripts/gen_build_info.py - do not edit or commit.\n"
        "#pragma once\n"
        '#define INKDECK_VERSION "%s"\n'
        '#define INKDECK_BUILD_ID "%s"\n' % (version(project_dir), build_id(project_dir))
    )

    out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, HEADER)
    try:
        with open(out_path, encoding="utf-8") as f:
            unchanged = f.read() == content
    except OSError:
        unchanged = False
    if not unchanged:
        with open(out_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)

    env.AppendUnique(CPPPATH=[out_dir])  # noqa: F821


main()
