"""PlatformIO pre-build hook: generate inkdeck_build.h with the build's git commit.

INKDECK_BUILD_ID is the short commit hash, with a "+" when the working tree has uncommitted
changes ("425d25c", "425d25c+"), or "dev" outside a git checkout. The System screen shows it
next to the firmware version, so after an update over Wi-Fi (src/ota.h) you can see which build
the board is running.

The header goes into the build directory and is rewritten only when its content changes, so only
the file that includes it (src/sysinfo.cpp) recompiles after a commit.
"""
import os
import subprocess

Import("env")  # noqa: F821 - SCons injects Import into extra scripts

HEADER = "inkdeck_build.h"


def git(project_dir, *args):
    try:
        return subprocess.run(
            ["git", *args], cwd=project_dir, capture_output=True, text=True, check=True, timeout=10
        ).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None


def build_id(project_dir):
    commit = git(project_dir, "rev-parse", "--short", "HEAD")
    if not commit:
        return "dev"
    dirty = git(project_dir, "status", "--porcelain", "--untracked-files=no")
    return commit + ("+" if dirty else "")


def main():
    project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
    content = (
        "// Generated by scripts/gen_build_info.py - do not edit or commit.\n"
        "#pragma once\n"
        '#define INKDECK_BUILD_ID "%s"\n' % build_id(project_dir)
    )

    out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, HEADER)
    try:
        with open(out_path, encoding="utf-8") as f:
            unchanged = f.read() == content
    except OSError:
        unchanged = False
    if not unchanged:
        with open(out_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)

    env.AppendUnique(CPPPATH=[out_dir])  # noqa: F821


main()
